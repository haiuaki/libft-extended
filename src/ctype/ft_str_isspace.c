#include "str.h"

int	ft_str_isspace(const char *str)
{
	size_t	i;

	if (!str)
		return (0);
	i = 0;
	while (str[i])
	{
		if (!((str[i] >= 9 && str[i] <= 13) || str[i] == 32))
			return (0);
		i++;
	}
	return (1);
}
